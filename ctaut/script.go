func (script *RegistrationScript) Deserialize(r io.Reader) error {
	var err error

	if script.ctAutIdentifier, script.scriptType, err = readPrefix(r, Registration); err != nil {
		return err
	}
	if script.ctAutName, err = ReadVarBytes(r, MaxCTAUTNameLength, "name"); err != nil {
		return err
	}
	if script.ctAutSymbol, err = ReadVarBytes(r, MaxCTAUTSymbolLength, "symbol"); err != nil {
		return err
	}
	if script.baseUnitName, err = ReadVarBytes(r, MaxBaseUnitLength, "baseUnit"); err != nil {
		return err
	}
	if script.subUnitName, err = ReadVarBytes(r, MaxSubUnitLength, "subUnit"); err != nil {
		return err
	}
	if script.unitScale, err = ReadVarInt(r); err != nil {
		return err
	}
	if script.ctAutMemo, err = readAutMemo(r); err != nil {
		return err
	}

	if script.plannedTotalAmount, err = ReadVarInt(r); err != nil {
		return err
	}
	if script.issuerTokens, err = readIssuerTokens(r); err != nil {
		return err
	}
	if script.mintThreshold, err = ReadByte(r); err != nil {
		return err
	}
	if script.reregisterThreshold, err = ReadByte(r); err != nil {
		return err
	}

	var expireHeight uint64
	if expireHeight, err = ReadVarInt(r); err != nil {
		return err
	}
	script.expireHeight = int32(expireHeight)

	if script.outAutRootTokenNum, err = ReadByte(r); err != nil {
		return err
	}
	if script.memo, err = readMemo(r); err != nil {
		return err
	}

	return script.SanityCheck()
}

func (script *RegistrationScript) SanityCheck() error {
	if script.scriptType != Registration {
		return errors.New("unexpected type for registration script")
	}

	if !bytes.Equal(script.ctAutIdentifier[:], zeroIdentifier[:]) {
		return ErrInValidAUTTx
	}
	if len(script.ctAutName) == 0 || len(script.ctAutName) > MaxCTAUTNameLength {
		return ErrInValidAUTTx
	}
	if len(script.ctAutSymbol) == 0 || len(script.ctAutSymbol) > MaxCTAUTSymbolLength {
		return ErrInValidAUTTx
	}

	if len(script.baseUnitName) == 0 || len(script.baseUnitName) > MaxBaseUnitLength {
		return ErrInValidAUTTx
	}
	if len(script.subUnitName) == 0 || len(script.subUnitName) > MaxSubUnitLength {
		return ErrInValidAUTTx
	}
	if script.unitScale == 0 || script.unitScale > MaxAmount || script.unitScale > script.plannedTotalAmount {
		return ErrInValidAUTTx
	}
	if len(script.ctAutMemo) > MaxCTAUTMemoLength {
		return ErrInValidAUTTx
	}

	if script.plannedTotalAmount == 0 || script.plannedTotalAmount > MaxAmount {
		return ErrInValidAUTTx
	}
	if len(script.issuerTokens) == 0 || len(script.issuerTokens) > MaxIssuerNum {
		return ErrInValidAUTTx
	}
	if int(script.mintThreshold) == 0 || int(script.mintThreshold) > len(script.issuerTokens) {
		return ErrInValidAUTTx
	}
	if int(script.reregisterThreshold) == 0 || int(script.reregisterThreshold) > len(script.issuerTokens) {
		return ErrInValidAUTTx
	}
	if script.expireHeight <= 0 || script.expireHeight > math.MaxInt32 {
		return ErrInValidAUTTx
	}

	if script.outAutRootTokenNum == 0 {
		return ErrInValidAUTTx
	}
	if len(script.memo) > MaxMemoLength {
		return ErrInValidAUTTx
	}

	return nil
}

